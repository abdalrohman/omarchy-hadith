#!/usr/bin/env python3
"""Build HadithTranslations.js: Turkish and Russian text for the bundled hadiths.

Source: fawazahmed0/hadith-api (https://github.com/fawazahmed0/hadith-api, Unlicense),
the dataset HadithData.js itself comes from (same hadith numbering and identical
Arabic/English text). Only editions that exist are used; any hadith without a usable
translation falls back to English in the UI.

Cleanup strips publisher scaffolding only (cross-reference lists, commentary appendices,
"click here" link text, footnote markers). The translation wording itself is not changed.

Usage:  python3 -I tools/build_translations.py [plugin_dir]
"""
import json
import re
import sys
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

API = "https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1/editions"

PREFIX = {"tr": "tur", "ru": "rus"}

SOURCES = {
    "tr": "Turkish: fawazahmed0/hadith-api (translator not credited upstream)",
    "ru": "Russian: fawazahmed0/hadith-api, from isnad.link (Sahih al-Bukhari: Abdullah Nirsha and the editors of daura.com)",
}

# Cleanup rules live in the library helper so bundled and downloaded text match.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "bin"))
from hadith_library import TRANSLATIONS as EDITIONS, clean_ru, clean_tr  # noqa: E402

CLEAN = {"tr": clean_tr, "ru": clean_ru}


def load_bundled(plugin_dir):
    s = (plugin_dir / "HadithData.js").read_text(encoding="utf-8")
    i = s.index("var BUILTIN_HADITHS")
    j = s.index("[", i)
    depth = 0
    for k in range(j, len(s)):
        if s[k] == "[":
            depth += 1
        elif s[k] == "]":
            depth -= 1
            if depth == 0:
                return json.loads(s[j:k + 1])
    raise ValueError("BUILTIN_HADITHS not found")


def fetch(edition, number):
    url = f"{API}/{edition}/{number}.json"
    last = None
    for attempt in range(3):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "omarchy-hadith-build"})
            with urllib.request.urlopen(req, timeout=40) as r:
                data = json.loads(r.read().decode("utf-8"), strict=False)
            hadiths = data.get("hadiths") or []
            return (hadiths[0].get("text") or "").strip() if hadiths else ""
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return ""
            last = e
        except Exception as e:
            last = e
        time.sleep(1.5 * (attempt + 1))
    raise RuntimeError(f"failed to fetch {url}: {last!r}")


def main():
    plugin_dir = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent)
    bundled = load_bundled(plugin_dir)
    jobs = [(h["id"], lang, h["collection"], h["hadithNumber"])
            for h in bundled for lang in ("tr", "ru") if h["collection"] in EDITIONS[lang]]
    with ThreadPoolExecutor(8) as ex:
        texts = list(ex.map(lambda j: fetch(f"{PREFIX[j[1]]}-{j[2]}", j[3]), jobs))

    out = {}
    for (hid, lang, _, _), raw in zip(jobs, texts):
        text = CLEAN[lang](raw) if raw else ""
        if len(text) > 20:
            out.setdefault(hid, {})[lang] = text

    order = [h["id"] for h in bundled if h["id"] in out]
    lines = [
        "// ============================================================================",
        "// HadithTranslations.js — Turkish & Russian text for the bundled hadiths",
        "// Generated by tools/build_translations.py; do not edit by hand.",
        "// ============================================================================",
        ".pragma library",
        "",
        "var LANGUAGES = " + json.dumps([
            {"code": "en", "label": "English"},
            {"code": "tr", "label": "Türkçe"},
            {"code": "ru", "label": "Русский"},
        ], ensure_ascii=False) + ";",
        "",
        "var SOURCES = " + json.dumps(SOURCES, ensure_ascii=False, indent=2) + ";",
        "",
        "var TRANSLATIONS = {",
    ]
    for n, hid in enumerate(order):
        comma = "," if n < len(order) - 1 else ""
        lines.append(f"  {json.dumps(hid)}: {json.dumps(out[hid], ensure_ascii=False)}{comma}")
    lines += ["};", ""]
    (plugin_dir / "HadithTranslations.js").write_text("\n".join(lines), encoding="utf-8")

    counts = {lang: sum(lang in v for v in out.values()) for lang in ("tr", "ru")}
    print(f"wrote HadithTranslations.js: {counts} of {len(bundled)} bundled hadiths")


if __name__ == "__main__":
    main()
